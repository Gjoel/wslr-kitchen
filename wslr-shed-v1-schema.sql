-- WSLR Bike Shed v1
-- Tracks what goes into and comes out of the bike shed, and who took it.
-- Safe to run more than once.

-- the things on the shelves
create table if not exists shed_items (
  id          bigint generated by default as identity primary key,
  name        text not null,
  category    text,
  unit        text,
  quantity    numeric not null default 0,
  par_level   numeric,          -- "should have": how many when fully stocked
  min_level   numeric,          -- "reorder at": at or below this it is low
  supplier    text,
  location    text,             -- shelf spot
  notes       text,
  active      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- every in, out and count correction, with who did it
create table if not exists shed_movements (
  id          bigint generated by default as identity primary key,
  item_id     bigint not null references shed_items(id) on delete cascade,
  kind        text not null check (kind in ('out','in','adjust')),
  change      numeric not null,
  qty_after   numeric,
  who         text,
  supplier    text,
  receipt     text,
  note        text,
  created_at  timestamptz not null default now()
);
create index if not exists shed_movements_item_idx on shed_movements(item_id, created_at desc);
create index if not exists shed_movements_time_idx on shed_movements(created_at desc);

-- categories, each with its own colour
create table if not exists shed_categories (
  id     bigint generated by default as identity primary key,
  name   text not null unique,
  colour text not null default 'c7',
  sort   int not null default 100
);

-- the tap-to-choose lists managed under Settings
create table if not exists shed_options (
  id       bigint generated by default as identity primary key,
  list     text not null check (list in ('people','names','suppliers','units','spots')),
  value    text not null,
  category text,                 -- only used by the item names list
  created_at timestamptz not null default now(),
  unique (list, value)
);

alter table shed_items enable row level security;
alter table shed_movements enable row level security;
alter table shed_categories enable row level security;
alter table shed_options enable row level security;
drop policy if exists anon_all_shed_items on shed_items;
create policy anon_all_shed_items on shed_items for all to anon using (true) with check (true);
drop policy if exists anon_all_shed_movements on shed_movements;
create policy anon_all_shed_movements on shed_movements for all to anon using (true) with check (true);
drop policy if exists anon_all_shed_categories on shed_categories;
create policy anon_all_shed_categories on shed_categories for all to anon using (true) with check (true);
drop policy if exists anon_all_shed_options on shed_options;
create policy anon_all_shed_options on shed_options for all to anon using (true) with check (true);

-- One call records the movement and updates the count together, so two
-- people tapping at once can never leave the count and the history out of step.
--   out    : p_qty taken off the shelf
--   in     : p_qty put on the shelf
--   adjust : p_qty is the new count (stocktake or a correction)
create or replace function shed_move(
  p_item bigint, p_kind text, p_qty numeric,
  p_who text default null, p_note text default null,
  p_supplier text default null, p_receipt text default null
) returns shed_items
language plpgsql
set search_path = public
as $$
declare
  it shed_items;
  delta numeric;
begin
  select * into it from shed_items where id = p_item for update;
  if not found then raise exception 'Item not found'; end if;
  if p_kind = 'out' then
    if nullif(trim(coalesce(p_who, '')), '') is null then raise exception 'Choose who is taking it'; end if;
    delta := -abs(coalesce(p_qty, 0));
  elsif p_kind = 'in' then delta := abs(coalesce(p_qty, 0));
  elsif p_kind = 'adjust' then delta := coalesce(p_qty, 0) - it.quantity;
  else raise exception 'Unknown movement %', p_kind;
  end if;
  update shed_items set quantity = quantity + delta, updated_at = now()
    where id = p_item returning * into it;
  insert into shed_movements(item_id, kind, change, qty_after, who, supplier, receipt, note)
    values (p_item, p_kind, delta, it.quantity,
            nullif(trim(p_who), ''), nullif(trim(p_supplier), ''), nullif(trim(p_receipt), ''), nullif(trim(p_note), ''));
  return it;
end;
$$;
grant execute on function shed_move(bigint, text, numeric, text, text, text, text) to anon;

